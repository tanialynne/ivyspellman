/**
 * The opening pages, set on a sheet of cream paper. A teaser, not the whole chapter:
 * several books are in KDP Select, so excerpts stay well under 10% of the book.
 * Text comes from constants/Excerpts.ts (generated by scripts/extract-excerpts.mjs).
 */
function FirstPages({ book }: { book: Book }) {
  const excerpt = EXCERPTS[book.slug];
  if (!excerpt) return null;
  const hook = excerpt.hook;
  return (
    <section className="jb-sec jb-wine jb-firstpages" id="first-pages" data-stars="8">
      <div className="jb-wrap">
        <div className="jb-fp-intro">
          <Eyebrow>The first pages</Eyebrow>
          <h2>
            {hook.slice(0, -1).map((line) => (
              <span key={line}>
                {line}
                <br />
              </span>
            ))}
            <em>{hook.at(-1)}</em>
          </h2>
          <p className="jb-fp-src">
            {book.title}
            <br />
            {excerpt.label}
          </p>
        </div>
        <article className="jb-sheet" aria-label={`Excerpt from ${book.title}, ${excerpt.label.toLowerCase()}`}>
          <p className="chap">{excerpt.label}</p>
          {excerpt.title && <h3>{excerpt.title}</h3>}
          <div className="prose">
            {excerpt.paragraphs.map((para, i) =>
              para === "* * *" ? (
                <p key={i} className="brk" aria-hidden="true">
                  ✦ ✦ ✦
                </p>
              ) : (
                // Our own manuscript text; the only markup in it is <em>.
                <p key={i} dangerouslySetInnerHTML={{ __html: para }} />
              ),
            )}
          </div>
          <div className="more">
            {book.buyLink ? (
              <GoldButton as="a" href={book.buyLink} target="_blank" rel="noopener noreferrer">
                {book.preorder ? "Preorder to keep reading" : "Keep reading on Amazon"}
              </GoldButton>
            ) : (
              <Link className="jb-sheet-link" href="#newsletter">
                Tell me when it&apos;s out
              </Link>
            )}
          </div>
        </article>
      </div>
    </section>
  );
}

/**
 * The series in reading order, current book ringed in gold.
 */
function ReadingOrder({ book }: { book: Book }) {
  const series = SERIES.find((s) => s.key === book.series)!;
  const books = booksInSeries(book.series);
  const idx = books.indexOf(book);
  const next = books[idx + 1];
  return (
    <section className={`jb-sec jb-${book.series === "hfh" ? "navy" : "teal"}`} data-stars="10">
      <div className="jb-wrap">
        <SectionHead
          split
          eyebrow="Reading order"
          title={series.name}
          lede={next ? `Up next: ${next.title}. Every book is a complete romance, so you can also jump in anywhere.` : series.intro}
        />
        <div className="jb-order" style={books.length < 6 ? { gridTemplateColumns: `repeat(${books.length}, minmax(0, 170px))` } : undefined}>
          {books.map((b) => (
            <Link key={b.slug} href={`/books/${b.slug}`} className={b.slug === book.slug ? "here" : undefined} aria-current={b.slug === book.slug ? "page" : undefined}>
              <Image src={b.coverImage} alt={`${b.title} cover`} width={240} height={360} sizes="150px" />
              <span>{b.seriesLabel}</span>
            </Link>
          ))}
        </div>
      </div>
    </section>
  );
}

/**
 * This book's own reader reviews (Birchwood so far). HF&H pages show the Book 1 shuffle instead.
 */
function BookReviews({ book }: { book: Book }) {
  const reviews = reviewsFor(book.slug);
  if (!reviews.length) return null;
  const early = reviews.every((r) => r.source === "ARC");
  return (
    <section className="jb-sec jb-plum2" data-stars="16">
      <div className="jb-wrap">
        <Eyebrow center>{early ? "Early reader reviews" : "Reader reviews"}</Eyebrow>
        <h2 className="jb-center">What readers are saying</h2>
        <div className="jb-rgrid">
          {reviews.map((r) => (
            <ReviewCard key={r.author} review={r} />
          ))}
        </div>
      </div>
    </section>
  );
}

/**
 * Single Book Page
 * Dynamic route for individual book details
 */
export default async function SingleBookPage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const book = BOOKS.find((b) => b.slug === slug);

  if (!book) {
    notFound();
  }

  const series = SERIES.find((s) => s.key === book.series)!;
  const seriesPosition = book.seriesPosition;

  return (
    <main className="jb bg-ivy-dark min-h-screen">
      {/* Book schema — generated from the same BOOKS entry the page renders,
          so it can never drift from what's on screen. */}
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: JSON.stringify({
            "@context": "https://schema.org",
            "@graph": [
              {
                "@type": "Book",
                "@id": `https://www.ivyspellman.com/books/${book.slug}#book`,
                name: book.title,
                alternativeHeadline: "A Cozy Witch Romantic Fantasy with Midlife Magic and Comedy",
                author: { "@id": "https://www.ivyspellman.com/#person" },
                url: `https://www.ivyspellman.com/books/${book.slug}`,
                image: `https://www.ivyspellman.com${book.coverImage}`,
                description: book.description,
                abstract: book.longDescription,
                inLanguage: "en-US",
                bookFormat: "https://schema.org/EBook",
                genre: ["Cozy fantasy", "Paranormal romance", "Romantic comedy", "Later in life romance"],
                ...(seriesPosition
                  ? {
                      position: seriesPosition,
                    }
                  : {}),
                isPartOf: {
                  "@type": "BookSeries",
                  "@id": `https://www.ivyspellman.com/#${series.anchor}`,
                  name: series.name,
                },
                ...(book.buyLink
                  ? {
                      offers: {
                        "@type": "Offer",
                        url: book.buyLink,
                        availability: book.comingSoon || book.preorder
                          ? "https://schema.org/PreOrder"
                          : "https://schema.org/InStock",
                      },
                    }
                  : {}),
              },
              {
                "@type": "BreadcrumbList",
                itemListElement: [
                  { "@type": "ListItem", position: 1, name: "Home", item: "https://www.ivyspellman.com" },
                  { "@type": "ListItem", position: 2, name: "Books", item: "https://www.ivyspellman.com/books" },
                  { "@type": "ListItem", position: 3, name: book.title, item: `https://www.ivyspellman.com/books/${book.slug}` },
                ],
              },
            ],
          }),
        }}
      />
      <Navigation />
      <BookHero book={book} />
      <BookDetails book={book} />
      <FirstPages book={book} />
      <ReadingOrder book={book} />
      {book.series === "hfh" ? (
        <RandomTestimonials title="Whispers from the readers" eyebrow="Five-star reviews of the series opener" ground="teal" />
      ) : (
        <BookReviews book={book} />
      )}
      <Newsletter />
      <Footer />
    </main>
  );
}
